#!/usr/bin/env python3
"""Generate the Unicode and HTML-entity tables used by mdq-core.

Writes crates/mdq-core/src/unitab.rs, crates/mdq-core/src/entities.rs and
tests/oracles/unitab.py (the frozen copy the tests compare against). The data comes from the
running Python's `unicodedata` and `html.entities`; run it again after a Python/Unicode upgrade
and commit the result (the three files must always be regenerated together).
"""
import html.entities
import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASCII_WS = " \t\n\f\r"


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    ver = unicodedata.unidata_version
    punct = ranges(lambda c: unicodedata.category(c)[0] in "PS")
    keep = ranges(lambda c: unicodedata.category(c)[0] in "LMN")
    zs = ranges(lambda c: unicodedata.category(c) == "Zs")
    fold = [(cp, chr(cp).casefold()) for cp in range(0x110000) if chr(cp).casefold() != chr(cp)]
    ents = sorted((k[:-1], v) for k, v in html.entities.html5.items() if k.endswith(";"))

    def rs(name, rg):
        body = "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in rg)
        return f"pub static {name}: &[(u32, u32)] = &[\n{body}];\n\n"

    def lit(s):
        return '"' + "".join(f"\\u{{{ord(ch):X}}}" for ch in s) + '"'

    rust = [f"//! GENERATED by scripts/gen_unicode_tables.py (Unicode {ver}). Do not edit.\n\n",
            f'pub const UNICODE_VERSION: &str = "{ver}";\n\n',
            rs("PUNCT", punct), rs("KEEP", keep), rs("ZS", zs),
            "pub static CASEFOLD: &[(u32, &str)] = &[\n",
            "".join(f"    (0x{cp:X}, {lit(s)}),\n" for cp, s in fold), "];\n"]
    (ROOT / "crates/mdq-core/src/unitab.rs").write_text("".join(rust))
    ent = ["//! GENERATED by scripts/gen_unicode_tables.py (HTML5 named character references). Do not edit.\n\n",
           "/// Name (without `&` and `;`) to replacement text, sorted by name.\n",
           "pub static ENTITIES: &[(&str, &str)] = &[\n",
           "".join(f'    ("{k}", {lit(v)}),\n' for k, v in ents), "];\n"]
    (ROOT / "crates/mdq-core/src/entities.rs").write_text("".join(ent))
    py = ['"""GENERATED by scripts/gen_unicode_tables.py. Frozen Unicode data the tests compare against."""\n',
          f'UNICODE_VERSION = "{ver}"\n', f"PUNCT = {punct!r}\n", f"KEEP = {keep!r}\n", f"ZS = {zs!r}\n",
          f"CASEFOLD = {dict(fold)!r}\n"]
    (ROOT / "tests/oracles/unitab.py").write_text("".join(py))
    print(f"Unicode {ver}: {len(punct)} punct, {len(keep)} keep, {len(zs)} zs ranges, {len(fold)} folds, {len(ents)} entities")


if __name__ == "__main__":
    sys.exit(main())
